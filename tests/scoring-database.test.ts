import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
import { expect, it } from 'vitest';
import { randomInt, randomUUID } from 'node:crypto';
import { createTournament, updateMatch, type Tournament } from '../src/domain/tournament';
import { createGame, gameAction, gameView, keypadHit, type Game } from '../src/domain/scoring';
import { hashToken } from '../src/server/security';
it('Spieler-Leases, Zuschauer, parallele Games und Abschluss sind transaktional abgesichert',async()=>{
  const db=new PGlite();
  const owner=hashToken('live-owner'),a=hashToken('live-a'),b=hashToken('live-b'),other=hashToken('live-other'),takeover=hashToken('live-takeover'),c=hashToken('live-c');
  const call=(name:string,args:unknown[])=>db.query(`select public.${name}(${args.map((_,i)=>'$'+(i+1)).join(',')})`,args);
  try {
    await db.exec('create role anon;create role authenticated;create role service_role bypassrls;create publication supabase_realtime;');
    await db.exec(await readFile(new URL('../supabase/migrations/003_setup_complete.sql',import.meta.url),'utf8'));
    await db.exec(await readFile(new URL('../supabase/migrations/008_admin_players.sql',import.meta.url),'utf8'));
    await db.query("insert into public.sessions(token_hash,role,tournament_id,credential_version,expires_at) values($1,'owner',null,1,now()+interval '1 day')",[owner]);
    let t=createTournament({id:randomUUID(),name:'Parallelspiel',names:Array.from({length:8},(_,i)=>'Spieler '+i),mode:'knockout',groupSize:4,advancePerGroup:2,scoring:{start:301,out:'double',legsToWin:1}},randomInt,randomUUID);
    t.status='running';t.startedAt=new Date().toISOString();
    await call('create_tournament',[t,{admin_hash:'',editor_link_hash:hashToken(t.id),editor_pin_hash:'pin',editor_secret:'secret'},owner]);
    for(const key of [a,b,other,takeover,c])await db.query("insert into public.sessions(token_hash,role,tournament_id,credential_version,expires_at) values($1,'editor',$2,1,now()+interval '1 day')",[key,t.id]);
    const m=t.matches[0],second=t.matches[1],players=m.players as [string,string];
    await call('claim_player',[a,players[0],false]);await call('claim_player',[b,players[1],false]);
    await call('claim_player',[other,t.matches[2].players[0],false]);
    await expect(call('claim_player',[takeover,players[0],false])).rejects.toThrow('PLAYER_IN_USE');
    await call('claim_player',[takeover,players[0],true]);
    expect((await db.query<{s:unknown}>('select public.read_session($1) as s',[a])).rows[0].s).toBeNull();
    await expect(call('claim_player',[a,randomUUID(),false])).rejects.toThrow();
    await expect(call('choose_tournament_player',[owner,t.id,players[0],false])).rejects.toThrow('PLAYER_IN_USE');
    await call('choose_tournament_player',[owner,t.id,players[0],true]);
    expect((await db.query<{s:unknown}>('select public.read_session($1) as s',[takeover])).rows[0].s).toBeNull();
    expect((await db.query<{s:{role:string;playing_tournament_id:string;participant_id:string}}>('select public.read_session($1) as s',[owner])).rows[0].s).toMatchObject({role:'owner',playing_tournament_id:t.id,participant_id:players[0]});
    await expect(call('choose_tournament_player',[b,randomUUID(),players[1],false])).rejects.toThrow();
    await expect(call('choose_tournament_player',[b,t.id,null,false])).rejects.toThrow();
    await expect(call('choose_tournament_player',[other,t.id,players[0],false])).rejects.toThrow('PLAYER_IN_USE');
    await call('choose_tournament_player',[other,t.id,players[0],true]);
    expect((await db.query<{s:{role:string;participant_id:string|null}}>('select public.read_session($1) as s',[owner])).rows[0].s).toMatchObject({role:'owner',participant_id:null});
    await call('choose_tournament_player',[owner,t.id,players[0],true]);
    await call('choose_tournament_player',[owner,t.id,null,false]);
    expect((await db.query<{s:{role:string;participant_id:string|null}}>('select public.read_session($1) as s',[owner])).rows[0].s).toMatchObject({role:'owner',participant_id:null});
    await call('choose_tournament_player',[owner,t.id,players[0],false]);
    await db.exec(await readFile(new URL('../supabase/migrations/008_admin_players.sql',import.meta.url),'utf8'));
    await db.query("insert into public.sessions(token_hash,role,tournament_id,credential_version,expires_at) values($1,'editor',$2,1,now()+interval '1 day')",[other,t.id]);
    await call('choose_tournament_player',[other,t.id,t.matches[2].players[0],false]);
    const keyA=owner;
    await db.exec(await readFile(new URL('../supabase/migrations/009_board_images.sql',import.meta.url),'utf8'));

    let g=createGame(players,t.scoring!);
    let next=updateMatch(t,m.id,{legs:[0,0],status:'running',forfeited:null}).tournament;next.version=t.version+1;next.updatedAt=new Date().toISOString();
    const persisted=(g:Game)=>({...g,activePlayer:g.players[gameView(g).active]});
    await expect(call('write_game',[t.id,m.id,0,other,persisted(g),next,t.version])).rejects.toThrow();
    await call('write_game',[t.id,m.id,0,keyA,persisted(g),next,t.version]);t=next;
    const connection=randomUUID(),frame='data:image/jpeg;base64,/9j/AA==',stamp=new Date().toISOString();
    const imageArgs=[t.id,m.id,keyA,connection,'bull:1','frame',frame,stamp];
    await call('write_board_image',imageArgs);
    expect((await db.query('select image from public.match_board_images')).rows).toHaveLength(1);
    await expect(call('write_board_image',[t.id,m.id,other,connection,'bull:1','frame',frame,stamp])).rejects.toThrow('Nur eigene Matches');
    expect(((await call('write_board_image',[t.id,m.id,keyA,connection,'playing:50','frame',frame,stamp])).rows[0] as {write_board_image:boolean}).write_board_image).toBe(false);
    await call('write_board_image',[t.id,m.id,keyA,randomUUID(),'bull:1','clear',null,stamp]);
    expect((await db.query<{image:string}>('select image from public.match_board_images')).rows[0].image).toBe(frame);
    await call('write_board_image',[t.id,m.id,keyA,connection,'bull:1','clear',null,stamp]);
    expect((await db.query<{image:string|null}>('select image from public.match_board_images')).rows[0].image).toBeNull();
    await db.exec('set role anon');
    await expect(db.query('select image from public.match_board_images')).rejects.toThrow();
    await expect(call('write_board_image',imageArgs)).rejects.toThrow();
    expect((await db.query('select * from public.match_games')).rows).toHaveLength(1);
    await expect(call('write_game',[t.id,m.id,1,keyA,persisted(g),null,null])).rejects.toThrow();
    await db.exec('reset role');
    const manual=updateMatch(t,m.id,{legs:[1,0],status:'finished',forfeited:null}).tournament;manual.version=t.version+1;
    await expect(call('save_tournament',[manual,t.version,keyA,'score',{action:'score',matchId:m.id}])).rejects.toThrow('gerade gespielt');
    await expect(call('save_tournament',[manual,t.version,other,'score',{action:'score',matchId:m.id}])).rejects.toThrow('eigene Matches');
    await call('claim_player',[c,second.players[0],false]);
    const otherGame=createGame(second.players as [string,string],t.scoring!);
    next=updateMatch(t,second.id,{legs:[0,0],status:'running',forfeited:null}).tournament;next.version=t.version+1;next.updatedAt=new Date().toISOString();
    await call('write_game',[t.id,second.id,0,c,persisted(otherGame),next,t.version]);t=next;
    expect((await db.query('select * from public.match_games')).rows).toHaveLength(2);
    async function move(player:string,key:string,action:Parameters<typeof gameAction>[2]) {
      const expected=g.version;const result=gameAction(g,player,action);
      let final:Tournament|null=null;
      if(result.phase==='finished'){final=updateMatch(t,m.id,{legs:[gameView(result).legs[0],gameView(result).legs[1]],status:'finished',forfeited:null}).tournament;final.version=t.version+1;final.updatedAt=new Date().toISOString();}
      await call('write_game',[t.id,m.id,expected,key,persisted(result),final,final?t.version:null]);
      g=result;if(final)t=final;
    }
    await move(players[0],keyA,{type:'bull',hit:keypadHit(25,2)});await move(players[1],b,{type:'bull',hit:keypadHit(25,1)});await move(players[0],keyA,{type:'next'});await move(players[1],b,{type:'next'});
    const invalid=gameAction(g,players[0],{type:'dart',hit:keypadHit(20,3)});
    await expect(call('write_game',[t.id,m.id,g.version,b,persisted(invalid),null,null])).rejects.toThrow('Reihe');
    const results=await Promise.allSettled([call('write_game',[t.id,m.id,g.version,keyA,persisted(invalid),null,null]),call('write_game',[t.id,m.id,g.version,keyA,persisted(invalid),null,null])]);
    expect(results.filter(r=>r.status==='fulfilled')).toHaveLength(1);g=invalid;
    for(let i=0;i<2;i++)await move(players[0],keyA,{type:'dart',hit:keypadHit(20,3)});
    await move(players[0],keyA,{type:'next'});await move(players[1],b,{type:'dart',hit:keypadHit(0,1)});await move(players[1],b,{type:'next'});
    for(const hit of [keypadHit(20,3),keypadHit(11,3),keypadHit(14,2)])await move(players[0],keyA,{type:'dart',hit});
    await move(players[0],keyA,{type:'next'});
    expect(g.phase).toBe('finished');expect(t.matches[0].legs).toEqual([1,0]);expect(t.matches[0].winner).toBe(players[0]);
    const snapshot=(await db.query<{state:Tournament}>('select state from public.public_tournament_snapshots where id=$1',[t.id])).rows[0].state;
    expect(snapshot.matches[0].winner).toBe(players[0]);
    expect((await db.query<{state:Game}>('select state from public.match_games where tournament_id=$1 and match_id=$2',[t.id,second.id])).rows[0].state).toMatchObject({phase:'bull',version:1});
    const archived={...t,status:'archived',version:t.version+1};
    await expect(call('save_tournament',[archived,t.version,owner,'archive',{action:'status'}])).rejects.toThrow('gerade gespielt');
    // End or reset the second game, then archiving hides game snapshots from spectators.
    const restored=updateMatch(t,second.id,{legs:[null,null],status:'pending',forfeited:null}).tournament;restored.version=t.version+1;
    await call('reset_game',[t.id,second.id,owner,restored,t.version]);t=restored;
    await call('save_tournament',[{...t,status:'archived',version:t.version+1},t.version,owner,'archive',{action:'status'}]);
    await db.exec('set role anon');expect((await db.query('select * from public.match_games')).rows).toHaveLength(0);
  }finally{await db.close();}
},30000);
